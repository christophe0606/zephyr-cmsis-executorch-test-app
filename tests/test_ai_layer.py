"""Exercise pack-backed generation and CLI defaults without ML dependencies."""

from contextlib import chdir, redirect_stderr, redirect_stdout
import io
import os
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

import create_ai_layer as generator
from ai_layer_backends import ExportedModel, cmsis, zephyr


class AiLayerTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(dir=Path(__file__).resolve().parent)
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name).resolve()
        self.mlops = self.root / "example.cbuild-mlops.yml"
        self.mlops.write_text("cbuild-mlops: {}\n")
        (self.root / "example.cbuild-pack.yml").write_text(
            "cbuild-pack:\n  resolved-packs:\n"
            "    - resolved-pack: PyTorch::ExecuTorch@1.6.0\n"
            "      selected-by-pack: [PyTorch::ExecuTorch@1.6.0]\n"
        )
        self.pack_root = self.root / "packs"
        self.pack = self.pack_root / "PyTorch/ExecuTorch/1.6.0"
        (self.pack / "src/registration").mkdir(parents=True)
        (self.pack / "zephyr").mkdir()
        (self.pack / "src/registration/RegisterAllKernels.cpp").write_text(
            '#ifdef RTE_ML_EXECUTORCH_OP_PORTABLE_ADD\nKernel("aten::add.out", fn)\n#endif\n'
            '#ifdef RTE_ML_EXECUTORCH_OP_CORTEX_M_MAXIMUM\nKernel("aten::maximum.out", fn)\n#endif\n'
        )
        self.kconfig = self.pack / "zephyr/Kconfig"
        self.kconfig.write_text(
            'config CMSIS_EXECUTORCH_OP_PORTABLE_ADD\n\tbool "Add"\n'
            'config CMSIS_EXECUTORCH_OP_CORTEX_M_MAXIMUM\n\tbool "Maximum"\n'
            '\tdepends on CMSIS_NN\n'
        )
        (self.pack / "PyTorch.ExecuTorch.pdsc").write_text(
            '<package><components><component Cgroup="ExecuTorch Operators" Csub="Portable add">'
            '<RTE_Components_h>#define RTE_ML_EXECUTORCH_OP_PORTABLE_ADD</RTE_Components_h>'
            '</component></components></package>'
        )
        self.model = ExportedModel(b"test program", ("aten::add.out",))
        env = patch.dict(os.environ, {"CMSIS_PACK_ROOT": str(self.pack_root)})
        env.start()
        self.addCleanup(env.stop)

    def test_discovery_and_explicit_override(self):
        with chdir(self.root):
            self.assertEqual(generator.resolve_mlops_file(), self.mlops)
            (self.root / "second.cbuild-mlops.yml").write_text("")
            with self.assertRaisesRegex(ValueError, "multiple.*supply a path"):
                generator.resolve_mlops_file()
            self.assertEqual(generator.resolve_mlops_file(self.mlops.name), self.mlops)

    def test_no_input_found(self):
        with chdir(self.pack):
            with self.assertRaisesRegex(ValueError, "no .*cbuild-mlops.yml"):
                generator.resolve_mlops_file()

    def test_invalid_input_suffix(self):
        with self.assertRaisesRegex(ValueError, "expected a"):
            generator.resolve_mlops_file("example.yml")

    def test_pack_version_comes_from_lock(self):
        self.assertEqual(cmsis.executorch_pack(self.mlops), self.pack)
        (self.root / "example.cbuild-pack.yml").write_text("cbuild-pack:\n  resolved-packs: []\n")
        with self.assertRaisesRegex(ValueError, "not among the resolved packs"):
            zephyr.render(self.mlops, {}, self.model)

    def test_zephyr_registration_and_output(self):
        entry, metadata = zephyr.render(self.mlops, {}, self.model)
        self.assertEqual(entry, self.root / "ai_layer/CMakeLists.txt")
        self.assertEqual(metadata, {
            "CMakeLists.txt": zephyr.CMAKE,
            "components.conf": zephyr.COMPONENTS,
            "operators.conf": "# Generated by west ailayer -- do not edit.\n"
                              "CONFIG_CMSIS_EXECUTORCH_OP_PORTABLE_ADD=y\n",
        })

    def test_cortex_operator_only_generates_cmsis_executorch_configs(self):
        model = ExportedModel(b"", ("aten::maximum.out",))
        _, metadata = zephyr.render(self.mlops, {}, model)
        for name in ("components.conf", "operators.conf"):
            for line in metadata[name].splitlines():
                if line.startswith("CONFIG_"):
                    self.assertTrue(line.startswith("CONFIG_CMSIS_EXECUTORCH"), line)
        self.assertIn("CONFIG_CMSIS_EXECUTORCH_OP_CORTEX_M_MAXIMUM=y\n", metadata["operators.conf"])

    def test_missing_kconfig_option(self):
        self.kconfig.write_text("")
        with self.assertRaisesRegex(ValueError, "operator Kconfig options missing.*PORTABLE_ADD"):
            zephyr.render(self.mlops, {}, self.model)

    def test_unsupported_operator(self):
        with self.assertRaisesRegex(ValueError, "unsupported operators: aten::missing.out"):
            zephyr.render(self.mlops, {}, ExportedModel(b"", ("aten::missing.out",)))

    def test_generation_defaults_and_cmsis_mode(self):
        with chdir(self.root), patch.object(generator, "compile_spec"), \
                patch.object(generator, "export_model", return_value=self.model), \
                redirect_stdout(io.StringIO()):
            self.assertEqual(generator.create_ai_layer(), self.root / "ai_layer/CMakeLists.txt")
            self.assertEqual((self.root / "ai_layer/model.pte").read_bytes(), self.model.pte)
            self.assertIn("0x74, 0x65", (self.root / "ai_layer/model_pte.c").read_text())
            layer = generator.create_ai_layer(backend="cmsis")
            self.assertEqual(layer, self.root / "ai_layer/ai_layer.clayer.yml")
            self.assertIn("PyTorch::ExecuTorch@1.6.0", layer.read_text())
            self.assertIn("Machine Learning:ExecuTorch Operators:Portable add", layer.read_text())

    def test_cli_dispatch(self):
        for options, backend in (([], "zephyr"), (["--backend", "cmsis"], "cmsis"),
                                 (["--mode", "zephyr", str(self.mlops)], "zephyr")):
            with self.subTest(options=options), chdir(self.root), \
                    patch.object(generator, "run_in_venv") as venv, \
                    patch.object(generator, "create_ai_layer") as create, \
                    patch("sys.argv", ["create_ai_layer.py", *options]):
                generator.main()
                venv.assert_called_once_with()
                create.assert_called_once_with(self.mlops, backend=backend)

    def test_cli_rejects_invalid_mode_before_export(self):
        with patch("sys.argv", ["create_ai_layer.py", "--backend", "invalid"]), \
                patch.object(generator, "run_in_venv") as venv, redirect_stderr(io.StringIO()):
            with self.assertRaises(SystemExit) as error:
                generator.main()
            self.assertEqual(error.exception.code, 2)
            venv.assert_not_called()


if __name__ == "__main__":
    unittest.main()
